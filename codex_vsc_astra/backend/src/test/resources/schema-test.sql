CREATE TABLE TB_USER (
 USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 USERNAME VARCHAR2(50) NOT NULL UNIQUE, PASSWORD VARCHAR2(255) NOT NULL,
 EMAIL VARCHAR2(100) NOT NULL UNIQUE, ROLE VARCHAR2(20) DEFAULT 'ROLE_USER' NOT NULL,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE TB_POST (
 POST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 TITLE VARCHAR2(200) NOT NULL, CONTENT CLOB NOT NULL,
 USER_ID NUMBER NOT NULL REFERENCES TB_USER(USER_ID), VIEW_COUNT NUMBER DEFAULT 0 NOT NULL,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
