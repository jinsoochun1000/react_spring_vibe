-- Oracle 18c XE / AL32UTF8. Reference DDL for an EMPTY schema only.
-- Existing USERSTK6 tables already exist. Do not execute this on that schema.
-- Application startup never executes this file; no DROP/TRUNCATE statements.
CREATE TABLE TB_USER (
  USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
  USERNAME VARCHAR2(50 BYTE) NOT NULL,
  PASSWORD VARCHAR2(255 BYTE) NOT NULL,
  EMAIL VARCHAR2(100 BYTE) NOT NULL,
  ROLE VARCHAR2(20 BYTE) DEFAULT 'ROLE_USER' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TB_USER PRIMARY KEY (USER_ID),
  CONSTRAINT UQ_TB_USER_USERNAME UNIQUE (USERNAME),
  CONSTRAINT UQ_TB_USER_EMAIL UNIQUE (EMAIL)
);
CREATE TABLE TB_POST (
  POST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
  TITLE VARCHAR2(200 BYTE) NOT NULL,
  CONTENT CLOB NOT NULL,
  USER_ID NUMBER NOT NULL,
  VIEW_COUNT NUMBER DEFAULT 0 NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TB_POST PRIMARY KEY (POST_ID),
  CONSTRAINT FK_TB_POST_USER FOREIGN KEY (USER_ID) REFERENCES TB_USER(USER_ID)
);
